create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  source text not null,
  title text not null,
  url text not null unique,
  url_hash text,
  snippet text,
  published_text text,
  score integer not null default 0,
  reasons text,
  stack_hits jsonb not null default '[]'::jsonb,
  intent_hits jsonb not null default '[]'::jsonb,
  query text,
  status text not null default 'NEW' check (status in ('NEW','SAVED','APPLIED','CONTACTED','REPLIED','CLIENT','DISCARDED')),
  notified boolean not null default false,
  found_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_leads_status_score on public.leads(status, score desc);
create index if not exists idx_leads_found_at on public.leads(found_at desc);
create index if not exists idx_leads_source on public.leads(source);

-- Server-side service-role access only. Do not expose the service-role key in browser/mobile code.
alter table public.leads enable row level security;
